  for(const key of ['index','step','blank','ink','laser','effects'])assert.deepEqual(after[key],before[key]);
  await jump(2);
  const restored=await page.evaluate(snapshot=>htmlDeck.restoreState(snapshot),before);
  for(const key of ['index','step','blank','ink','laser','effects'])assert.deepEqual(restored[key],before[key]);
  assert.equal(await audience.locator('#audience-blank').isVisible(),true);
  await page.locator('#controller-restore').click();
