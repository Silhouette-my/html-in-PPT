  await jump(7);await audience.locator('#spring-run').click();
  await page.waitForFunction(()=>Number(document.querySelector('#spring-simulation').dataset.frame)>3);
  // Visibility is injected so CI can deterministically exercise background-owner scheduling.
  await audience.evaluate(()=>{window.ownerFrames=0;const original=requestAnimationFrame;window.requestAnimationFrame=callback=>{window.ownerFrames++;return original(callback);};});
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'));});
  await audience.waitForFunction(()=>window.ownerFrames>3);
  assert.equal((await page.evaluate(()=>htmlDeck.getState())).effects.physics.running,true);
  await page.evaluate(()=>{delete document.hidden;document.dispatchEvent(new Event('visibilitychange'));});
  await page.locator('#spring-run').click();
  assert.ok(await audience.locator('#spring-canvas').evaluate(el=>el.toDataURL())===await page.locator('#spring-canvas').evaluate(el=>el.toDataURL()),'paused audience canvas matches the owner frame');
  await jump(8);
  const cube=await audience.locator('#cube-drag').boundingBox();
  await audience.mouse.move(cube.x+30,cube.y+30);await audience.mouse.down();await audience.mouse.move(cube.x+100,cube.y+60);await audience.mouse.up();
  assert.equal(await audience.locator('#cube-yaw').inputValue(),await page.locator('#cube-yaw').inputValue());
