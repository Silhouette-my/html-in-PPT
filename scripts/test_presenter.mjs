  await page.locator('#controller-laser').click();
  await page.mouse.move(stage.x+stage.width*.25,stage.y+stage.height*.6);
  const laser=await page.evaluate(()=>htmlDeck.getState().laser);
  assert.equal(laser.visible,true);assert.ok(Math.abs(laser.x-400)<3&&Math.abs(laser.y-540)<3,'owner laser uses unscaled slide coordinates');
  assert.ok(Math.abs(await audience.locator('#audience-laser').evaluate(el=>Number.parseFloat(el.style.left))-laser.x)<.01);
  assert.ok(Math.abs(await audience.locator('#audience-laser').evaluate(el=>Number.parseFloat(el.style.top))-laser.y)<.01);
